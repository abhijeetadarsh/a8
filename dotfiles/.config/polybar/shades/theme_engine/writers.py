def polybar(p, path):
    """[color] section included by shades/config.ini.

    Key names are frozen: bars.ini, modules.ini and user_modules.ini reference
    ${color.shade1..8}, ${color.foreground} and friends in ~100 places.
    """
    lines = [f"; {HEADER}", "", "[color]", "; main"]
    for k in ("background", "foreground", "foreground-alt"):
        lines.append(f"{k} = {p[k]}")
    lines += ["", "; shades (surface ramp, tipping into the accent at the top)"]
    for i in range(1, 9):
        lines.append(f"shade{i} = {p[f'shade{i}']}")
    lines += ["", "; semantic - prefer these in new modules"]
    for k in ("base", "mantle", "crust", "surface0", "surface1", "surface2",
              "overlay0", "overlay1", "text", "subtext", "muted", "accent",
              "accent_dim", "urgent", "warning", "success", "info",
              "red", "green", "yellow", "blue", "magenta", "cyan"):
        lines.append(f"{k} = {p[k]}")
    lines.append("")
    return _write(path, "\n".join(lines))


