"""
Writers - one function per program that needs to be told about the palette.

Two output roots, and the split is not arbitrary:

  ~/.cache/theme/          for programs that can be pointed at an absolute
                           path (nvim via dofile, starship via STARSHIP_CONFIG,
                           shell scripts via source).

  ~/.config/<program>/     for programs whose include mechanism only reliably
                           resolves a file sitting next to their main config
                           (polybar, rofi, i3, kitty, dunst, gtk).

The second group is why postinstall stows with --no-folding: it makes
~/.config/kitty a real directory holding a symlinked kitty.conf, so a
generated current-theme.conf lands beside it instead of inside the git repo.
"""

import json
import os

HEADER = "generated by theme_engine - edits are overwritten on every wallpaper change"


def _write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(content)
    return path


def _rgba(hex_color, alpha="ff"):
    return hex_color + alpha


# ============================================================================
# ~/.cache/theme/
# ============================================================================


def shell(p, path):
    """Plain shell variables. Sourced by the i3lock scripts and anything else."""
    lines = [f"# {HEADER}", ""]
    for k, v in sorted(p.items()):
        lines.append(f'THEME_{k.upper().replace("-", "_")}="{v}"')
    lines.append("")
    return _write(path, "\n".join(lines))


def json_dump(p, path):
    """The palette as data, for debugging and for anything added later."""
    return _write(path, json.dumps(p, indent=2, sort_keys=True) + "\n")


