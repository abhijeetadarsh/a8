def xresources(p, path):
    """*.color0..15 for the X resource database.

    Anything old-school that reads xrdb - i3lock, xterm, the odd Java app -
    picks the palette up from here.
    """
    ansi = [
        "black", "red", "green", "yellow", "blue", "magenta", "cyan", "white",
        "bright_black", "bright_red", "bright_green", "bright_yellow",
        "bright_blue", "bright_magenta", "bright_cyan", "bright_white",
    ]
    lines = [f"! {HEADER}", ""]
    lines.append(f"*.background: {p['base']}")
    lines.append(f"*.foreground: {p['text']}")
    lines.append(f"*.cursorColor: {p['cursor']}")
    lines.append("")
    for i, name in enumerate(ansi):
        lines.append(f"*.color{i}: {p[name]}")
    lines.append("")
    return _write(path, "\n".join(lines))
